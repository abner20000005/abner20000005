class Reserva:
    def __init__(self, id_reserva, fecha, estado, id_lector, lector, id_libro, libro):
        self.id_reserva = id_reserva
        self.fecha = fecha
        self.estado = estado
        self.id_lector = id_lector
        self.lector = lector
        self.id_libro = id_libro
        self.libro = libro