class Devolucion:
    def __init__(self, id_devolucion, fecha, dias_retraso, multa, id_prestamo, lector, libro, codigo):
        self.id_devolucion = id_devolucion
        self.fecha = fecha
        self.dias_retraso = dias_retraso
        self.multa = multa
        self.id_prestamo = id_prestamo
        self.lector = lector
        self.libro = libro
        self.codigo = codigo