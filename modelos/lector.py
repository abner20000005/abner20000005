class Lector:
    def __init__(self, id_lector, nombre, apellido, identidad, telefono, correo, direccion, estado, id_tipo, tipo):
        self.id_lector = id_lector
        self.nombre = nombre
        self.apellido = apellido
        self.identidad = identidad
        self.telefono = telefono
        self.correo = correo
        self.direccion = direccion
        self.estado = estado
        self.id_tipo = id_tipo
        self.tipo = tipo